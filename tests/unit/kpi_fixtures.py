"""Deterministic tandem-line event builder (theory oracle) for KPI tests.

Not a test module. ``simulate_line`` models a single-server FIFO tandem line
through the real message classes with explicit ``ts`` (never wall clock), so
hand-computable cycle times and busy totals can be compared with KPI output.

``tests/fixtures/kpi_events.jsonl`` was generated by ``simulate_line`` with
``RECORDED_ARGS`` below (default recipes, event ids seeded for determinism).
"""

import random
import uuid
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

from pizza.common.constants import STATIONS
from pizza.common.envelope import (
    Message,
    OpCompleted,
    OpDispatched,
    OpFailed,
    OpStarted,
    OrderLifecycle,
    RunPaused,
    RunResumed,
    StationStatus,
    encode,
    parse_message,
)
from pizza.common.recipes import load_all_recipes

RUN = "r1"
T0 = datetime(2026, 1, 1, tzinfo=UTC)
FIXTURE_PATH = Path(__file__).resolve().parent.parent / "fixtures" / "kpi_events.jsonl"

# 6 orders (mixed products/qty) created every 20 s; bake is the bottleneck so
# bake WAIT > 0 appears.
RECORDED_ARGS: dict[str, Any] = {
    "orders": [
        ("o1", "margherita", 2, 0.0),
        ("o2", "pepperoni", 3, 20.0),
        ("o3", "veggie", 1, 40.0),
        ("o4", "margherita", 3, 60.0),
        ("o5", "pepperoni", 2, 80.0),
        ("o6", "veggie", 3, 100.0),
    ],
    "run_id": RUN,
    "track_in_s": 0.5,
}


def ts(n: int) -> datetime:
    return T0 + timedelta(milliseconds=n)


def at(offset_s: float, t0: datetime = T0) -> datetime:
    """T0 + offset, rounded to whole milliseconds so JSON round-trips exactly."""
    return t0 + timedelta(milliseconds=round(offset_s * 1000))


@dataclass
class Simulated:
    messages: list[Message]
    cycle_time_s: dict[str, float]
    busy_s: dict[str, float]


def simulate_line(
    orders: list[tuple[str, str, int, float]],
    recipes: dict[str, dict[str, float]] | None = None,
    *,
    run_id: str = RUN,
    t0: datetime = T0,
    track_in_s: float = 0.0,
    seed: int = 7,
    due_offset_s: float | dict[str, float] | None = None,
) -> Simulated:
    """Build every fact of a FIFO single-server tandem line run.

    Args:
        due_offset_s: Optional due date offset from created_ts.
                      If None (default), uses 3600.0 seconds (1 hour).
                      If a float, applies to all orders.
                      If a dict, maps order_id -> offset_s.
    """
    recipes = recipes if recipes is not None else load_all_recipes()
    rng = random.Random(seed)
    # Default due offset: 1 hour after created_ts
    if due_offset_s is None:
        default_offset = 3600.0
        due_offset_map: dict[str, float] | None = None
    elif isinstance(due_offset_s, dict):
        default_offset = 3600.0  # Fallback for orders not in dict
        due_offset_map = due_offset_s
    else:
        default_offset = float(due_offset_s)
        due_offset_map = None

    def mk(cls: Any, machine: str, when: float, **fields: Any) -> Message:
        msg = cls.make(run_id=run_id, machine_id=machine, ts=at(when, t0), **fields)
        return msg.model_copy(update={"event_id": uuid.UUID(int=rng.getrandbits(128), version=4)})

    msgs: list[Message] = []
    free: dict[str, float] = dict.fromkeys(STATIONS, 0.0)
    busy: dict[str, float] = dict.fromkeys(STATIONS, 0.0)
    cycle: dict[str, float] = {}

    ordered = sorted(enumerate(orders), key=lambda p: (p[1][3], p[0]))
    for _, (oid, product, qty, created) in ordered:
        # Compute due_ts using due_offset_s parameter or default
        offset = due_offset_map.get(oid, default_offset) if due_offset_map else default_offset
        due = at(created + offset, t0)
        created_dt = at(created, t0)
        life = {
            "order_id": oid,
            "product": product,
            "qty": qty,
            "due_ts": due,
            "created_ts": created_dt,
        }
        msgs.append(mk(OrderLifecycle, "scheduler", created, state="created", **life))
        msgs.append(mk(OrderLifecycle, "scheduler", created, state="released", **life))
        ready = created
        for station in STATIONS:
            unit = recipes[station][product]
            dispatched = max(ready, free[station])
            started = dispatched + track_in_s
            completed = started + qty * unit
            free[station] = completed
            busy[station] += qty * unit
            cmd = uuid.UUID(int=rng.getrandbits(128), version=4)
            msgs.append(
                mk(
                    OpDispatched,
                    "scheduler",
                    dispatched,
                    order_id=oid,
                    step=station,
                    visit=1,
                    qty=qty,
                    product=product,
                    command_event_id=cmd,
                    ready_ts=at(ready, t0),
                )
            )
            op = {
                "order_id": oid,
                "step": station,
                "visit": 1,
                "attempt": 1,
                "qty": qty,
                "product": product,
                "command_event_id": cmd,
            }
            msgs.append(mk(OpStarted, station, started, redelivered=False, **op))
            msgs.append(mk(StationStatus, station, started, status="busy"))
            msgs.append(mk(OpCompleted, station, completed, duration_s=qty * unit, **op))
            msgs.append(mk(StationStatus, station, completed, status="idle"))
            ready = completed
        msgs.append(mk(OrderLifecycle, "scheduler", ready, state="completed", **life))
        cycle[oid] = ready - created
    msgs.sort(key=lambda m: m.ts)
    return Simulated(messages=msgs, cycle_time_s=cycle, busy_s=busy)


def pause_fact(offset_s: float, *, run_id: str = RUN, t0: datetime = T0) -> Message:
    return RunPaused.make(run_id=run_id, machine_id="scheduler", ts=at(offset_s, t0))


def resume_fact(offset_s: float, *, run_id: str = RUN, t0: datetime = T0) -> Message:
    return RunResumed.make(run_id=run_id, machine_id="scheduler", ts=at(offset_s, t0))


def to_jsonl(msgs: list[Message]) -> str:
    return "".join(encode(m).decode() + "\n" for m in msgs)


def from_jsonl(text: str) -> list[Message]:
    return [parse_message(line.encode()) for line in text.splitlines() if line.strip()]


def shuffled(msgs: list[Message], seed: int) -> list[Message]:
    out = list(msgs)
    random.Random(seed).shuffle(out)
    return out


def with_duplicates(msgs: list[Message], seed: int, n: int) -> list[Message]:
    """Append ``n`` exact copies of random messages, then shuffle."""
    rng = random.Random(seed)
    out = list(msgs) + [rng.choice(msgs) for _ in range(n)]
    rng.shuffle(out)
    return out


def recorded_simulation() -> Simulated:
    return simulate_line(**RECORDED_ARGS)


def cooling_rework_log(*, with_v2_start: bool = True) -> list[Message]:
    """Phase 6.2 D-10 log: v1 fails at t=5; v2 dispatched at 10.4 (ready_ts = 5).

    WAIT for v2 = TTL + backlog queueing = 5.4 s; Track-In = dispatch -> start.
    """
    cmd1, cmd2 = uuid.uuid4(), uuid.uuid4()
    op = {"order_id": "o1", "step": "spin", "attempt": 1, "qty": 1}
    life = {
        "run_id": RUN, "machine_id": "scheduler", "order_id": "o1", "product": "margherita",
        "qty": 1, "due_ts": at(3600), "created_ts": at(0),
    }
    msgs: list[Message] = [
        OrderLifecycle.make(ts=at(0), state="created", **life),
        OrderLifecycle.make(ts=at(0), state="released", **life),
        OpDispatched.make(
            run_id=RUN, machine_id="scheduler", ts=at(1), visit=1, command_event_id=cmd1,
            ready_ts=at(0), **op,
        ),
        OpStarted.make(
            run_id=RUN, machine_id="spin", ts=at(2), visit=1, redelivered=False,
            command_event_id=cmd1, **op,
        ),
        OpFailed.make(
            run_id=RUN, machine_id="spin", ts=at(5), visit=1, reason="boom",
            command_event_id=cmd1, **op,
        ),
        OpDispatched.make(
            run_id=RUN, machine_id="scheduler", ts=at(10.4), visit=2, command_event_id=cmd2,
            ready_ts=at(5), **op,
        ),
    ]  # fmt: skip
    if with_v2_start:
        msgs.append(
            OpStarted.make(
                run_id=RUN, machine_id="spin", ts=at(10.6), visit=2, redelivered=False,
                command_event_id=cmd2, **op,
            )
        )  # fmt: skip
    return msgs
