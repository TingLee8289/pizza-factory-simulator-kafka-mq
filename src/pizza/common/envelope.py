class RecipeSnapshot(Fact):
    """Full recipe table published at run start (Phase 8 D-09).

    Covers exactly the seven stations and three products with finite positive times.
    """

    model_config = ConfigDict(frozen=True, extra="ignore", allow_inf_nan=False)

    type: Literal["recipe.snapshot"] = "recipe.snapshot"
    recipes: dict[str, dict[str, float]]

    @field_validator("recipes")
    @classmethod
    def _full_table(cls, value: dict[str, dict[str, float]]) -> dict[str, dict[str, float]]:
        if set(value) != set(STATIONS):
            raise ValueError("recipe snapshot must cover exactly the seven stations")
        for station, table in value.items():
            if set(table) != set(PRODUCTS):
                raise ValueError(f"station {station!r} must define exactly {sorted(PRODUCTS)}")
            for seconds in table.values():
                if not math.isfinite(seconds) or seconds <= 0:
                    raise ValueError(f"station {station!r} has a non-positive/non-finite time")
        return value


