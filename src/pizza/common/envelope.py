"""Unified message envelope shared by every service (INFRA-03).

The base envelope carries exactly six required fields (D-11) plus the
discriminator ``type``. Per-type fields are added as new union members
(Phase 2: job, run, station status and op facts; Phase 3: order.submitted,
order.lifecycle, op.dispatched and RunParams on run.started; Phase 4:
kpi.snapshot; Phase 5: run.pause/run.resume/run.reset/generator.set_rate/
scheduler.set_rule commands, run.paused/run.resumed facts, optional order
``source``; Phase 7: RuleChanged fact, RoundClose command, ComparisonResult
fact, DueKpi and extended RunParams; Phase 8: RecipeChanged and RecipeSnapshot
config-change facts; quick-wrj: ManualOrderRequest generator RPC command;
quick-et6: TimeScaleChanged fact on sim.timescale). Optional field additions do
not bump ``schema_version``.

Phase 5 decision (D-04): pause/resume facts live on ``station.events`` with
machine_id "scheduler" so the KPI and dashboard folds can derive frozen
intervals. There is no RunReset fact; runs are isolated by run_id only (D-05).

Phase 07.2 decision (D-05/D-06): the optional order ``rush`` boolean is replaced
by a numeric ``priority`` (1..99, smaller = more urgent). Legacy payloads that
still carry ``rush`` are parsed by a before-validator (``true -> 10``,
``false``/missing -> 50); ``schema_version`` stays 1 so old events still replay
(D-11: priority.changed fact, lot.set_priority command).
"""

