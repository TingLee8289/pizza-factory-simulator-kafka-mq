def _legacy_rush_to_priority(data: Any) -> Any:
    """Map a legacy ``rush`` boolean onto ``priority`` (Phase 07.2 D-06).

    Only acts on dict input and only when ``priority`` is absent, so an explicit
    ``priority`` always wins. ``rush`` is exactly ``True`` -> 10, anything else
    (``False``/missing/odd values) -> 50. The result is still validated by the
    model's ``ge``/``le`` field constraints (T-07.2-01). ``extra="ignore"`` on
    the envelope drops the stale ``rush`` key afterwards.
    """
    if isinstance(data, dict) and "priority" not in data and "rush" in data:
        legacy = PRIORITY_LEGACY_RUSH if data["rush"] is True else PRIORITY_DEFAULT
        return {**data, "priority": legacy}
    return data


