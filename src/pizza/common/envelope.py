def _check_station_eta(value: dict[str, AwareDatetime] | None) -> dict[str, AwareDatetime] | None:
    if value is None:
        return value
    if len(value) > len(STATIONS):
        raise ValueError("station_eta has too many entries")
    for key in value:
        if key not in STATIONS:
            raise ValueError(f"station_eta key {key!r} is not a station")
    return value


def _fmt_station_eta(value: dict[str, datetime] | None) -> dict[str, str] | None:
    return None if value is None else {k: _fmt_ts(v) for k, v in value.items()}


def _check_fail_flags(obj: Any) -> None:
    if obj.fail_step is not None and obj.fail_step not in STATIONS:
        raise ValueError(f"fail_step {obj.fail_step!r} is not a station")
    if (obj.poison or obj.fail_times is not None) and obj.fail_step is None:
        raise ValueError("poison/fail_times require fail_step")


