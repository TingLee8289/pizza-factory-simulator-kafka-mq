class RunParams(BaseModel):
    """Optional run parameters carried by RunStarted (D-17).

    Phase 7 extensions: rule, comparison_id, and round for dispatch rule and comparison features.
    """

    model_config = ConfigDict(frozen=True, extra="ignore")

    seed: int = 42
    arrival_rate: float = Field(default=1 / 35, gt=0, le=100)
    weights: dict[str, float] = Field(default_factory=lambda: dict.fromkeys(PRODUCTS, 1.0))
    k: float = Field(default=2.0, gt=0)
    k_max: float | None = None
    max_orders: int | None = Field(default=None, ge=1, le=MAX_ORDERS_CAP)
    # Phase 6 D-25: random breakdowns are off by default.
    random_breakdowns: bool = False
    # Phase 7 D-04: active dispatch rule (FIFO/EDD/SPT) for this run.
    rule: Literal["fifo", "edd", "spt"] | None = None
    # Phase 7 D-06: comparison_id groups multiple runs in a comparison round.
    comparison_id: str | None = Field(default=None, pattern=r"^c-[0-9a-z-]{1,36}$")
    # Phase 7 D-06: round number (1-3) within a comparison.
    round: int | None = Field(default=None, ge=1, le=3)
    # Phase 7.1: due source. "eta" = ETA at release x buffer_k; "theory" = legacy k/k_max.
    # buffer_k multiplies the ETA lead for generator auto orders (due = created + lead * buffer_k).
    # k/k_max apply only to due_mode="theory" and the ETA-RPC fallback (PD-1).
    due_mode: Literal["eta", "theory"] = "eta"
    buffer_k: float = Field(default=BUFFER_K_DEFAULT, ge=0.5, le=10, allow_inf_nan=False)

    @model_validator(mode="after")
    def _check(self) -> Self:
        for key, w in self.weights.items():
            if not re.match(SLUG_PATTERN, key):
                raise ValueError(f"invalid product slug {key!r}")
            if w < 0:
                raise ValueError("weights must be >= 0")
        if sum(self.weights.values()) <= 0:
            raise ValueError("weights must sum to > 0")
        if self.k_max is not None and self.k_max < self.k:
            raise ValueError("k_max must be >= k")
        return self


class JobCommand(Command):
    """Work order for one station (D-01/D-02); ``step`` is the station slug."""

    type: Literal["job.command"] = "job.command"
    order_id: str = Field(min_length=1)
    step: str = Field(min_length=1)
    visit: int = Field(default=1, ge=1)
    qty: int = Field(ge=1)
    unit_time_s: float | None = Field(default=None, gt=0)
    recipe: str | None = Field(default=None, pattern=SLUG_PATTERN)
    product: str | None = None
    # Phase 6 D-10: test-injection fail flags only.
    fail_times: int | None = Field(default=None, ge=0, le=99)
    poison: bool = False

    @model_validator(mode="after")
    def _bound_total(self) -> Self:
        if self.unit_time_s is None and self.recipe is None:
            raise ValueError("job needs a recipe or unit_time_s")
        if self.unit_time_s is not None and self.unit_time_s * self.qty > MAX_JOB_TOTAL_S:
            raise ValueError(f"unit_time_s * qty exceeds {MAX_JOB_TOTAL_S}s")
        return self


