class InvalidEnvelope(ValueError):
    """Raised when raw bytes cannot be parsed into a valid message."""


def new_event_id() -> uuid.UUID:
    """Return a fresh UUID4 event id."""
    return uuid.uuid4()


def utc_now() -> datetime:
    """Return the current UTC time, truncated to ms so it round-trips on the wire."""
    now = datetime.now(UTC)
    return now.replace(microsecond=now.microsecond // 1000 * 1000)


class Envelope(BaseModel):
    """Base envelope with the six required fields.

    ``run_id`` identifies one simulation run generated by a start action
    (not at service start); all messages in a run share it (D-06).
    ``machine_id`` is the station name; there is no separate station field (D-07).
    ``ts`` is serialised as UTC ISO8601 with a ``Z`` suffix (D-08).
    Unknown ``schema_version`` values are rejected (D-09).
    """

    model_config = ConfigDict(frozen=True, extra="ignore")

    event_id: uuid.UUID
    run_id: str = Field(min_length=1)
    line_id: str = Field(min_length=1)
    machine_id: str = Field(min_length=1)
    ts: AwareDatetime
    schema_version: Literal[1]
    type: str

    @field_serializer("ts")
    def _serialize_ts(self, value: datetime) -> str:
        utc = value.astimezone(UTC)
        return utc.isoformat(timespec="milliseconds").replace("+00:00", "Z")

    @classmethod
    def make(
        cls,
        *,
        run_id: str,
        machine_id: str,
        line_id: str = LINE_ID,
        ts: datetime | None = None,
        **extra: Any,
    ) -> Self:
        """Build a message with generated event_id, ts and schema_version."""
        return cls(
            event_id=new_event_id(),
            run_id=run_id,
            line_id=line_id,
            machine_id=machine_id,
            ts=ts if ts is not None else utc_now(),
            schema_version=1,
            **extra,
        )


